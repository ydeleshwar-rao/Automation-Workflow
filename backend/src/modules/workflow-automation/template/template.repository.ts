import type {
  Prisma,
  PrismaClient,
  Workflow,
  WorkflowFieldMapping,
  WorkflowNode,
  WorkflowTemplate,
  WorkflowTemplateMapping,
  WorkflowTemplateNode,
} from "@prisma/client";
import prisma from "../../../lib/prisma.js";

export interface CreateTemplateInput {
  name: string;
  description: string | null;
  category: string | null;
  tag: string | null;
  source_workflow_id: string;
  created_by: string;
  is_public: boolean;
  status: string;
}

export interface UpdateTemplateInput {
  name?: string;
  description?: string | null;
  category?: string | null;
  tag?: string | null;
  is_public?: boolean;
  status?: string;
  template_folder_id?: string | null;
}

export interface TemplateListFilter {
  created_by?: string;
  category?: string;
  status?: string;
  template_folder_id?: string;
  is_public?: boolean;
}

/** Ids are generated by the caller so mappings can reference nodes created in the same transaction. */
export type NewTemplateNode = Omit<Prisma.WorkflowTemplateNodeCreateManyInput, "template_id"> & { id: string };
export type NewTemplateMapping = Omit<Prisma.WorkflowTemplateMappingCreateManyInput, "template_id">;
export type NewWorkflowNode = Omit<Prisma.WorkflowNodeCreateManyInput, "workflow_id"> & { id: string };
export type NewWorkflowFieldMapping = Prisma.WorkflowFieldMappingCreateManyInput;

export interface NewWorkflowFromTemplate {
  name: string;
  tag: string | null;
  user_id: string;
  status: string;
}

export interface TemplateWithParts extends WorkflowTemplate {
  nodes: WorkflowTemplateNode[];
  mappings: WorkflowTemplateMapping[];
}

/**
 * Repository — the only place that talks to the database for workflow templates,
 * their nodes and mappings (one aggregate), including cloning to and from workflows.
 */
export class WorkflowTemplateRepository {
  constructor(private readonly database: PrismaClient = prisma) {}

  findSourceWorkflow(workflowId: string): Promise<Pick<Workflow, "id" | "tag"> | null> {
    return this.database.workflow.findUnique({
      where: { id: workflowId },
      select: { id: true, tag: true },
    });
  }

  findWorkflowNodes(workflowId: string): Promise<WorkflowNode[]> {
    return this.database.workflowNode.findMany({
      where: { workflow_id: workflowId },
      orderBy: { position: "asc" },
    });
  }

  findFieldMappings(nodeIds: string[]): Promise<WorkflowFieldMapping[]> {
    return this.database.workflowFieldMapping.findMany({ where: { workflow_node_id: { in: nodeIds } } });
  }

  /** Creates the template with its nodes and mappings atomically. */
  createWithParts(
    template: CreateTemplateInput,
    nodes: NewTemplateNode[],
    mappings: NewTemplateMapping[]
  ): Promise<{ template: WorkflowTemplate; nodes: WorkflowTemplateNode[] }> {
    return this.database.$transaction(async (transaction) => {
      const createdTemplate = await transaction.workflowTemplate.create({ data: template });
      const createdNodes = await transaction.workflowTemplateNode.createManyAndReturn({
        data: nodes.map((node) => ({ ...node, template_id: createdTemplate.id })),
      });
      await transaction.workflowTemplateMapping.createMany({
        data: mappings.map((mapping) => ({ ...mapping, template_id: createdTemplate.id })),
      });
      createdNodes.sort((first, second) => first.position - second.position);
      return { template: createdTemplate, nodes: createdNodes };
    });
  }

  findMany(filter: TemplateListFilter): Promise<WorkflowTemplate[]> {
    return this.database.workflowTemplate.findMany({
      where: filter,
      orderBy: { created_at: "desc" },
    });
  }

  findById(templateId: string): Promise<WorkflowTemplate | null> {
    return this.database.workflowTemplate.findUnique({ where: { id: templateId } });
  }

  findByIdWithParts(templateId: string): Promise<TemplateWithParts | null> {
    return this.database.workflowTemplate.findUnique({
      where: { id: templateId },
      include: { nodes: { orderBy: { position: "asc" } }, mappings: true },
    });
  }

  findActiveInFolder(folderId: string): Promise<WorkflowTemplate[]> {
    return this.database.workflowTemplate.findMany({
      where: { template_folder_id: folderId, status: "active" },
    });
  }

  /** Distinct, non-empty integration keys used by the given templates' nodes. */
  async findIntegrationKeys(templateIds: string[]): Promise<string[]> {
    const nodes = await this.database.workflowTemplateNode.findMany({
      where: { template_id: { in: templateIds }, integration_key: { not: "" } },
      select: { integration_key: true },
      distinct: ["integration_key"],
    });
    return nodes.map((node) => node.integration_key);
  }

  update(templateId: string, input: UpdateTemplateInput): Promise<WorkflowTemplate> {
    return this.database.workflowTemplate.update({ where: { id: templateId }, data: input });
  }

  /** Nodes and mappings are removed by ON DELETE CASCADE. */
  async delete(templateId: string): Promise<void> {
    await this.database.workflowTemplate.delete({ where: { id: templateId } });
  }

  /** Creates the workflow, its nodes and mappings, and bumps the template's usage count atomically. */
  createWorkflowFromTemplate(
    templateId: string,
    workflow: NewWorkflowFromTemplate,
    nodes: NewWorkflowNode[],
    mappings: NewWorkflowFieldMapping[]
  ): Promise<Workflow> {
    return this.database.$transaction(async (transaction) => {
      const createdWorkflow = await transaction.workflow.create({ data: workflow });
      await transaction.workflowNode.createMany({
        data: nodes.map((node) => ({ ...node, workflow_id: createdWorkflow.id })),
      });
      await transaction.workflowFieldMapping.createMany({ data: mappings });
      await transaction.workflowTemplate.update({
        where: { id: templateId },
        data: { usage_count: { increment: 1 } },
      });
      return createdWorkflow;
    });
  }
}

export const workflowTemplateRepository = new WorkflowTemplateRepository();
